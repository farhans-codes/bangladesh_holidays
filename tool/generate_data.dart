import 'dart:convert';
import 'dart:io';

import 'package:bangladesh_holidays/src/date.dart';
import 'package:bangladesh_holidays/src/holiday.dart';

/// Validate the source JSON and emit a deterministic, offline Dart snapshot.
Future<void> main(List<String> args) async {
  if (args.any((arg) => arg != '--check') || args.length > 1) {
    stderr.writeln('Usage: dart run tool/generate_data.dart [--check]');
    exitCode = 64;
    return;
  }
  final files = Directory('data')
      .listSync()
      .whereType<File>()
      .where((file) => file.path.endsWith('.json'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  if (files.isEmpty) {
    throw StateError('Run from the package root; no data found.');
  }
  final sources = <String, Map<String, dynamic>>{};
  final years = <Map<String, dynamic>>[];
  final ids = <String>{};
  final yearIds = <int>{};
  for (final file in files) {
    final data = object(jsonDecode(file.readAsStringSync()), 'year');
    keys(data, {
      'schemaVersion',
      'year',
      'verifiedOn',
      'scope',
      'sources',
      'holidays',
      'workingDays'
    });
    if (data['schemaVersion'] != 1 || data['year'] is! int) {
      fail('Invalid year/schema');
    }
    final year = data['year'] as int;
    if (!yearIds.add(year)) fail('Repeated year $year');
    parseDate(string(data, 'verifiedOn'));
    string(data, 'scope');
    final localSources = <String>{};
    for (final value in list(data, 'sources')) {
      final source = object(value, 'source');
      keys(source, {'id', 'title', 'url', 'publishedOn'});
      final id = string(source, 'id');
      if (!localSources.add(id) || sources.containsKey(id)) {
        fail('Repeated source $id');
      }
      string(source, 'title');
      final url = Uri.tryParse(string(source, 'url'));
      if (url == null || url.scheme != 'https' || url.host.isEmpty) {
        fail('Invalid source URL');
      }
      final published = parseDate(string(source, 'publishedOn'));
      if (published.isAfter(parseDate(string(data, 'verifiedOn')))) {
        fail('Source published after verification');
      }
      sources[id] = source;
    }
    void validateDateSource(Map<String, dynamic> row) {
      if (parseDate(string(row, 'date')).year != year) {
        fail('Date outside $year');
      }
      if (!localSources.contains(string(row, 'source'))) fail('Unknown source');
      string(row, 'nameEn');
      string(row, 'nameBn');
    }

    for (final value in list(data, 'holidays')) {
      final row = object(value, 'holiday');
      keys(row, {
        'id',
        'date',
        'nameEn',
        'nameBn',
        'type',
        'community',
        'districts',
        'excludedDistricts',
        'isEstimated',
        'source',
        'notesEn',
        'notesBn'
      });
      validateDateSource(row);
      final id = string(row, 'id');
      if (!id.startsWith('$year-') || !ids.add(id)) {
        fail('Invalid/repeated ID $id');
      }
      final type = HolidayType.values.byName(string(row, 'type'));
      if (type == HolidayType.company) {
        fail('Company closures cannot be official data');
      }
      if (row['isEstimated'] is! bool) fail('isEstimated must be explicit');
      if (type == HolidayType.optional && row['community'] == null) {
        fail('Missing community');
      }
      if (row['community'] != null) {
        HolidayCommunity.values.byName(string(row, 'community'));
      }
      final included = districts(row, 'districts');
      final excluded = districts(row, 'excludedDistricts');
      if (included.intersection(excluded).isNotEmpty) {
        fail('Contradictory districts');
      }
      if (row.containsKey('notesEn') != row.containsKey('notesBn')) {
        fail('Both note languages required');
      }
      for (final key in ['notesEn', 'notesBn']) {
        if (row.containsKey(key)) string(row, key);
      }
    }
    final workingDates = <String>{};
    for (final value in list(data, 'workingDays')) {
      final row = object(value, 'working day');
      keys(row, {'date', 'nameEn', 'nameBn', 'source'});
      validateDateSource(row);
      if (!workingDates.add(string(row, 'date'))) fail('Repeated working day');
    }
    years.add(data);
  }
  years.sort((a, b) => (a['year'] as int).compareTo(b['year'] as int));
  final out = StringBuffer(
      '// GENERATED by tool/generate_data.dart. Edit data/*.json instead.\n'
      "import '../holiday.dart';\n\n");
  final sourceNames = <String, String>{};
  for (final entry in sources.entries) {
    final name = '_source${sourceNames.length}';
    sourceNames[entry.key] = name;
    out.writeln('const $name = HolidaySource(');
    for (final key in ['id', 'title', 'url', 'publishedOn']) {
      out.writeln('  $key: ${quote(entry.value[key] as String)},');
    }
    out.writeln(');');
  }
  out.writeln('final generatedHolidays = List<Holiday>.unmodifiable([');
  for (final year in years) {
    final rows = list(year, 'holidays')
        .map((v) => object(v, 'holiday'))
        .toList()
      ..sort((a, b) {
        final order = string(a, 'date').compareTo(string(b, 'date'));
        return order != 0 ? order : string(a, 'id').compareTo(string(b, 'id'));
      });
    for (final row in rows) {
      out.writeln('Holiday(');
      for (final key in ['id', 'nameEn', 'nameBn', 'notesEn', 'notesBn']) {
        if (row.containsKey(key)) {
          out.writeln('$key: ${quote(row[key] as String)},');
        }
      }
      out.writeln('date: ${dateCode(row)}, type: HolidayType.${row['type']},');
      out.writeln(
          'isEstimated: ${row['isEstimated']}, source: ${sourceNames[row['source']]},');
      if (row['community'] != null) {
        out.writeln('community: HolidayCommunity.${row['community']},');
      }
      for (final key in ['districts', 'excludedDistricts']) {
        if (row[key] != null) {
          out.writeln(
              '$key: [${(row[key] as List).map((v) => 'District.$v').join(', ')}],');
        }
      }
      out.writeln('),');
    }
  }
  out.writeln(
      ']);\nfinal generatedWorkingDays = List<GovernmentWorkingDay>.unmodifiable([');
  for (final year in years) {
    for (final value in list(year, 'workingDays')) {
      final row = object(value, 'working day');
      out.writeln('GovernmentWorkingDay(date: ${dateCode(row)}, '
          'nameEn: ${quote(row['nameEn'] as String)}, '
          'nameBn: ${quote(row['nameBn'] as String)}, source: ${sourceNames[row['source']]}),');
    }
  }
  out.writeln(
      ']);\nfinal generatedCoverage = List<YearCoverage>.unmodifiable([');
  for (final year in years) {
    final refs = list(year, 'sources')
        .map((v) => sourceNames[object(v, 'source')['id']])
        .join(', ');
    out.writeln('YearCoverage(year: ${year['year']}, '
        'verifiedOn: ${quote(year['verifiedOn'] as String)}, '
        'scope: ${quote(year['scope'] as String)}, sources: [$refs]),');
  }
  out.writeln(']);');
  final temp = Directory.systemTemp.createTempSync('holiday-generator-');
  try {
    final draft = File('${temp.path}/holidays.dart')
      ..writeAsStringSync(out.toString());
    final formatted = await Process.run(Platform.resolvedExecutable, [
      'format',
      '--language-version=3.4',
      '--output=show',
      '--summary=none',
      draft.path
    ]);
    if (formatted.exitCode != 0) throw StateError('${formatted.stderr}');
    final code = formatted.stdout as String;
    final target = File('lib/src/data/holidays.g.dart');
    if (args.contains('--check')) {
      if (!target.existsSync() || target.readAsStringSync() != code) {
        stderr.writeln(
            'Generated data is stale. Run dart run tool/generate_data.dart');
        exitCode = 1;
        return;
      }
    } else {
      target.parent.createSync(recursive: true);
      target.writeAsStringSync(code);
    }
    stdout.writeln(
        'Validated ${ids.length} holidays across ${years.length} years.');
  } finally {
    temp.deleteSync(recursive: true);
  }
}

Never fail(String message) => throw FormatException(message);
Map<String, dynamic> object(Object? value, String context) =>
    value is Map<String, dynamic> ? value : fail('Expected object: $context');
List<dynamic> list(Map<String, dynamic> row, String key) =>
    row[key] is List ? row[key] as List : fail('Expected list: $key');
String string(Map<String, dynamic> row, String key) {
  final value = row[key];
  return value is String && value.trim().isNotEmpty
      ? value
      : fail('Expected text: $key');
}

void keys(Map<String, dynamic> row, Set<String> allowed) {
  final unknown = row.keys.toSet().difference(allowed);
  if (unknown.isNotEmpty) fail('Unknown keys: $unknown');
}

Set<District> districts(Map<String, dynamic> row, String key) {
  if (!row.containsKey(key)) return {};
  final values =
      list(row, key).map((v) => District.values.byName(v as String)).toList();
  if (values.toSet().length != values.length) fail('Repeated district');
  return values.toSet();
}

String quote(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
String dateCode(Map<String, dynamic> row) {
  final date = parseDate(string(row, 'date'));
  return 'DateTime.utc(${date.year}, ${date.month}, ${date.day})';
}
